#!/usr/bin/env python3
"""Assert successful compilation of the pinned inputs for four parser issues.

The source copies are private: compatibility edits never touch the supplied
source tree or a published dependency cache. A compiler crash fails the test.
"""

import argparse
import contextlib
from pathlib import Path
import shutil
import subprocess
import tempfile


def replace_once(path, before, after):
    text = path.read_text()
    assert text.count(before) == 1, (path, before)
    path.write_text(text.replace(before, after))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("issue", choices=["13204", "13207", "13208", "13213"])
    parser.add_argument("--roc", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--prepare-only", action="store_true")
    parser.add_argument("--work-dir", type=Path)
    args = parser.parse_args()
    if args.prepare_only and args.work_dir is None:
        parser.error("--prepare-only requires --work-dir")
    roc = args.roc.resolve()
    workspace = (
        contextlib.nullcontext(args.work_dir.resolve())
        if args.work_dir
        else tempfile.TemporaryDirectory(prefix=f"roc-{args.issue}-")
    )
    with workspace as directory:
        root = Path(directory)
        root.mkdir(parents=True, exist_ok=True)
        source = root / "parser"
        shutil.copytree(args.source, source)
        if args.issue in ("13207", "13208"):
            replace_once(
                source / "package/XmlNsCore.roc",
                "match opened.next() {",
                "match XmlNsCore.Reader.next(opened) {",
            )
        if args.issue == "13207":
            for value in (
                '[{ name: "outfilesuffix", value: ".temporary" }, { name: "outfilesuffix", value: ".html" }]',
                '[{ name: "outfilesuffix", value: ".temporary" }]',
            ):
                replace_once(
                    source / "package/AsciiDoc.roc",
                    "{ ..AsciiDocPreprocess.defaults, attributes: " + value + " }",
                    "AsciiDoc.Props.{ attributes: " + value + " }",
                )
            replace_once(
                source / "package/QIF.roc",
                "for split in (0).to(bytes.len() + 1)",
                "for split in (0.U64).to(bytes.len() + 1)",
            )
            replace_once(
                source / "package/MarkupNameTables.roc",
                "# Generated by scripts/markup/generate_vocabulary.py",
                "# Generated by scripts/generate.roc",
            )
        if args.issue == "13208":
            (source / "fuzz/XmlSpecConstrRepro.roc").write_text(
                '''app [main!] {
    cli: platform "https://github.com/roc-lang/basic-cli/releases/download/0.28.1/7brgwR8YUqfeGrkdfF1V4GPPN7DnP7ftqub9KcrTEZtr.tar.zst",
    parser: "../package/main.roc",
}
import parser.Xml

main! = |_args| {
    source : Stream(Try(List(U8), [Injected]))
    source = [Ok("<a/>".to_utf8()), Err(Injected)].iter().stream()
    for! _event in (Xml.decoder({})).read_stream(source) {
    }
    Ok({})
}
'''
            )
        commands = {
            "13204": ["check", "--no-cache", "-j1", "main.roc"],
            "13207": ["build", "--no-cache", "--fuzz", "fuzz/TextProperties.roc"],
            "13208": ["build", "--no-cache", "--opt=speed", "fuzz/XmlSpecConstrRepro.roc"],
            "13213": ["build", "--no-cache", "--fuzz", "fuzz/RecordsProperties.roc"],
        }
        command = [str(roc), *commands[args.issue]]
        if args.issue != "13204":
            command.append(f"--output={root / 'compiled'}")
        print(f"cwd: {source}\ncommand: {command}", flush=True)
        if args.prepare_only:
            return
        result = subprocess.run(command, cwd=source)
        assert result.returncode == 0, (
            f"issue #{args.issue}: valid source must compile, "
            f"compiler returned {result.returncode}"
        )
        if args.issue != "13204":
            assert (root / "compiled").is_file(), "compiler produced no executable"


if __name__ == "__main__":
    main()
