#!/usr/bin/env python3
"""Random Roc programs for the ARC model's differential fuzzing.

Keeps a typed environment of names (shape, shapes, tree, item, items, holder,
holders, strs, dict, int, bool) and composes small typed constructs at random:
each construct reads names of the kinds it needs and binds one new name of
its result kind. The constructs sit around what ARC, reuse and dismantling
rewrite: joins of tags (keep the incoming value or rebuild it), match arms
rebuilding a payload, variant swaps, record updates, List.map / update / set
rebuilding records and tags, trees rebuilt node by node, loops whose state is
a rebuilt tag, static data on one branch and fresh data on the other, Dicts
with live aliases, and aliasing through plain names, closures and lists.

Every value is also evaluated here in a pure reference semantics, and the
program ends with one `expect` per name comparing its rendering (show_*) with
the reference. Since every earlier name is checked after all later rebuilds,
an in-place reuse visible through another reference fails a check.

Runtime inputs come from `z` (0 at run time, opaque to constant folding).

usage: gen.py SEED [SIZE] [focus]
"""
import random
import sys

PAD = "heap-allocated-string-padding-0"   # value of "${pad}" at z == 0

PRELUDE = r'''# Generated by models/arc/gen.py
Shape := [Circle({ label : Str, r : I64 }), Rect({ label : Str, pts : List(I64) }), Dot]

Tree := [Leaf, Node(Tree, I64, Str, Tree)]

Item : { name : Str, tags : List(Str), n : I64 }

z0 : {} -> U64
z0 = |_| List.len(Str.split_on("a b", " ")) - 2

show_ints : List(I64) -> Str
show_ints = |xs| Str.join_with(xs.map(|x| x.to_str()), ",")

show_shape : Shape -> Str
show_shape = |s| match s {
	Circle({ label, r }) => "C(${label},${r.to_str()})"
	Rect({ label, pts }) => "R(${label},[${show_ints(pts)}])"
	Dot => "D"
}

show_shapes : List(Shape) -> Str
show_shapes = |xs| Str.join_with(xs.map(show_shape), ";")

show_tree : Tree -> Str
show_tree = |t| match t {
	Leaf => "."
	Node(l, k, s, r) => "(${show_tree(l)} ${k.to_str()}:${s} ${show_tree(r)})"
}

show_item : Item -> Str
show_item = |it| "I(${it.name},[${Str.join_with(it.tags, ",")}],${it.n.to_str()})"

show_items : List(Item) -> Str
show_items = |xs| Str.join_with(xs.map(show_item), ";")

r_of : Shape -> I64
r_of = |s| match s {
	Circle({ r, .. }) => r
	Rect({ pts, .. }) => List.sum(pts)
	Dot => 0
}

label_of : Shape -> Str
label_of = |s| match s {
	Circle({ label, .. }) => label
	Rect({ label, .. }) => label
	Dot => ""
}

relabel : Shape, Str -> Shape
relabel = |s, l| match s {
	Circle({ r, .. }) => Circle({ label: l, r })
	Rect({ pts, .. }) => Rect({ label: l, pts })
	Dot => Dot
}

grow : Shape, I64 -> Shape
grow = |s, d| match s {
	Circle(c) => Circle({ ..c, r: c.r + d })
	Rect(rc) => Rect({ ..rc, pts: rc.pts.append(d) })
	Dot => Dot
}

swap_kind : Shape -> Shape
swap_kind = |s| match s {
	Circle(c) => Rect({ label: c.label, pts: [c.r] })
	Rect(rc) => Circle({ label: rc.label, r: List.sum(rc.pts) })
	Dot => Dot
}

insert : Tree, I64, Str -> Tree
insert = |t, k, s| match t {
	Leaf => Node(Leaf, k, s, Leaf)
	Node(l, k2, s2, r) => if k < k2 Node(insert(l, k, s), k2, s2, r) else if k > k2 Node(l, k2, s2, insert(r, k, s)) else Node(l, k2, s, r)
}

bump : Tree, I64 -> Tree
bump = |t, d| match t {
	Leaf => Leaf
	Node(l, k, s, r) => Node(bump(l, d), k + d, s, bump(r, d))
}

rename_root : Tree, Str -> Tree
rename_root = |t, s| match t {
	Leaf => Leaf
	Node(l, k, _, r) => Node(l, k, s, r)
}

rename_item : Item, Str -> Item
rename_item = |{ tags, n, .. }, nm| { name: nm, tags, n }

Holder : { sh : Shape, k : I64 }

show_holder : Holder -> Str
show_holder = |h| "H(${show_shape(h.sh)},${h.k.to_str()})"

pick_label : Shape, Str, Bool -> Shape
pick_label = |s, l, keep| {
	if keep {
		return s
	}
	relabel(s, l)
}

show_entry : Dict(Str, List(Str)), Str -> Str
show_entry = |d, k| match d.get(k) {
	Ok(xs) => Str.join_with(xs, ",")
	Err(_) => "-"
}

show_dict : Dict(Str, List(Str)) -> Str
show_dict = |d| Str.join_with([Dict.len(d).to_str(), show_entry(d, "k0"), show_entry(d, "k1"), show_entry(d, "k2")], ";")

loop_grow : Shape, I64 -> Shape
loop_grow = |s, n| {
	var $acc = s
	for k in [1, 2, 3] {
		$acc = if k > n $acc else grow($acc, k)
	}
	$acc
}

'''

# ---- reference semantics -------------------------------------------------

def show_shape(s):
    if s[0] == "Circle":
        return f"C({s[1]['label']},{s[1]['r']})"
    if s[0] == "Rect":
        return f"R({s[1]['label']},[{','.join(str(x) for x in s[1]['pts'])}])"
    return "D"

def show_tree(t):
    if t is None:
        return "."
    l, k, s, r = t
    return f"({show_tree(l)} {k}:{s} {show_tree(r)})"

def show_item(it):
    return f"I({it['name']},[{','.join(it['tags'])}],{it['n']})"

def r_of(s):
    if s[0] == "Circle":
        return s[1]["r"]
    if s[0] == "Rect":
        return sum(s[1]["pts"])
    return 0

def relabel(s, l):
    if s[0] == "Circle":
        return ("Circle", {"label": l, "r": s[1]["r"]})
    if s[0] == "Rect":
        return ("Rect", {"label": l, "pts": list(s[1]["pts"])})
    return s

def grow(s, d):
    if s[0] == "Circle":
        return ("Circle", {**s[1], "r": s[1]["r"] + d})
    if s[0] == "Rect":
        return ("Rect", {**s[1], "pts": s[1]["pts"] + [d]})
    return s

def swap_kind(s):
    if s[0] == "Circle":
        return ("Rect", {"label": s[1]["label"], "pts": [s[1]["r"]]})
    if s[0] == "Rect":
        return ("Circle", {"label": s[1]["label"], "r": sum(s[1]["pts"])})
    return s

def insert(t, k, s):
    if t is None:
        return (None, k, s, None)
    l, k2, s2, r = t
    if k < k2:
        return (insert(l, k, s), k2, s2, r)
    if k > k2:
        return (l, k2, s2, insert(r, k, s))
    return (l, k2, s, r)

def bump(t, d):
    if t is None:
        return None
    l, k, s, r = t
    return (bump(l, d), k + d, s, bump(r, d))

def rename_root(t, s):
    if t is None:
        return None
    l, k, _, r = t
    return (l, k, s, r)

SHOW = {
    "shape": lambda v: show_shape(v),
    "shapes": lambda v: ";".join(show_shape(s) for s in v),
    "tree": show_tree,
    "item": show_item,
    "items": lambda v: ";".join(show_item(i) for i in v),
    "int": str,
    "ints": lambda v: ",".join(str(x) for x in v),
    "holder": lambda v: f"H({show_shape(v['sh'])},{v['k']})",
    "bool": lambda v: "T" if v else "F",
    "strs": lambda v: ",".join(v),
    "holders": lambda v: ";".join(f"H({show_shape(h['sh'])},{h['k']})" for h in v),
    "dict": lambda v: ";".join([str(len(v))] + [",".join(dict(v)[k]) if k in dict(v) else "-" for k in ("k0", "k1", "k2")]),
}
SHOW_FN = {"shape": "show_shape({})", "shapes": "show_shapes({})", "tree": "show_tree({})",
           "item": "show_item({})", "items": "show_items({})", "int": "{}.to_str()",
           "ints": "show_ints({})", "holder": "show_holder({})",
           "bool": "(if {} \"T\" else \"F\")", "strs": "Str.join_with({}, \",\")",
           "holders": "Str.join_with({}.map(show_holder), \";\")", "dict": "show_dict({})"}


def roc_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


class Gen:
    def __init__(self, seed):
        self.r = random.Random(seed)
        self.vars = []          # (name, kind, value, expr-to-read)
        self.lines = []
        self.n = 0
        self.helpers = []

    def fresh(self, p):
        self.n += 1
        return f"{p}{self.n}"

    def pick(self, kind):
        vs = [v for v in self.vars if v[1] == kind]
        return self.r.choice(vs) if vs else None

    def strx(self):
        k = self.r.randrange(100)
        if self.r.random() < 0.1:
            return '""', ""
        if self.r.random() < 0.5:
            return f'"s{k}"', f"s{k}"
        return f'"${{pad}}{k}"', f"{PAD}{k}"

    def intx(self):
        k = self.r.randrange(1, 20)
        return str(k), k

    def cond(self, kind, name, val):
        """A runtime condition and its value."""
        c = self.r.randrange(6)
        if kind == "shape" and c >= 4:
            lab = val[1]["label"] if val[0] != "Dot" else ""
            if c == 4:
                return f"label_of({name}).is_empty()", lab == ""
            other = self.r.choice([lab, "s1", ""])
            return f"label_of({name}) == {roc_str(other)}", lab == other
        if c == 0:
            return "z == 1", False
        if c == 1:
            return "z == 0", True
        if kind == "shape":
            k = self.r.randrange(0, 12)
            return f"r_of({name}) > {k}", r_of(val) > k
        if kind == "item":
            k = self.r.randrange(0, 12)
            return f"{name}.n > {k}", val["n"] > k
        return "z != 0", False

    def add(self, kind, expr, val, read=None, prefix=None):
        nm = self.fresh(prefix or kind[0])
        self.lines.append(f"\t{nm} = {expr}")
        self.vars.append((nm, kind, val, read or nm))
        return nm

    # -- constructs ---------------------------------------------------------
    def c_mk_shape(self):
        sx, sv = self.strx()
        ix, iv = self.intx()
        if self.r.random() < 0.5:
            return self.add("shape", f"Circle({{ label: {sx}, r: {ix} }})", ("Circle", {"label": sv, "r": iv}))
        jx, jv = self.intx()
        return self.add("shape", f"Rect({{ label: {sx}, pts: [{ix}, {jx}] }})", ("Rect", {"label": sv, "pts": [iv, jv]}))

    def shape_src(self):
        v = self.pick("shape")
        if v is None:
            self.c_mk_shape()
            v = self.vars[-1]
        return v

    def c_grow(self):
        nm, _, val, rd = self.shape_src()
        ix, iv = self.intx()
        if self.r.random() < 0.5:
            return self.add("shape", f"grow({rd}, {ix})", grow(val, iv))
        # inline match rebuilding the payload record
        e = (f"match {rd} {{ Circle(c) => Circle({{ ..c, r: c.r + {ix} }}), "
             f"Rect(rc) => Rect({{ ..rc, pts: rc.pts.append({ix}) }}), Dot => Dot }}")
        return self.add("shape", e, grow(val, iv))

    def c_join_shape(self):
        """One edge keeps the incoming tag, the other rebuilds it
        (https://github.com/roc-lang/roc/issues/13279)."""
        nm, _, val, rd = self.shape_src()
        cx, cv = self.cond("shape", rd, val)
        sx, sv = self.strx()
        ix, iv = self.intx()
        alt = self.r.randrange(4)
        if alt == 0:
            other, ov = f"relabel({rd}, {sx})", relabel(val, sv)
        elif alt == 1:
            other, ov = f"grow({rd}, {ix})", grow(val, iv)
        elif alt == 2:
            other, ov = f"swap_kind({rd})", swap_kind(val)
        else:
            other = (f"match {rd} {{ Circle(c) => Circle({{ ..c, label: {sx} }}), "
                     f"Rect(rc) => Rect({{ label: {sx}, pts: rc.pts }}), Dot => Dot }}")
            ov = relabel(val, sv)
        if self.r.random() < 0.5:
            e, v = f"if {cx} {rd} else {other}", (val if cv else ov)
        else:
            e, v = f"if {cx} {other} else {rd}", (ov if cv else val)
        # sometimes read it through a non-inlined reader right away
        return self.add("shape", e, v)

    def c_swap(self):
        nm, _, val, rd = self.shape_src()
        return self.add("shape", f"swap_kind({rd})", swap_kind(val))

    def c_fold_shape(self):
        nm, _, val, rd = self.shape_src()
        ks = [self.r.randrange(1, 9) for _ in range(self.r.randrange(1, 4))]
        lim = self.r.randrange(0, 9)
        sx, sv = self.strx()
        v = val
        for k in ks:
            v = v if k > lim else (relabel(v, sv) if k % 2 == 0 else grow(v, k))
        e = (f"[{', '.join(str(k) for k in ks)}].fold({rd}, |acc, k| if k > {lim} acc "
             f"else if k % 2 == 0 relabel(acc, {sx}) else grow(acc, k))")
        return self.add("shape", e, v)

    def c_shape_list(self):
        a = self.shape_src()
        b = self.shape_src()
        return self.add("shapes", f"[{a[3]}, {b[3]}]", [a[2], b[2]])

    def c_list_op(self):
        v = self.pick("shapes")
        if v is None:
            return self.c_shape_list()
        nm, _, val, rd = v
        op = self.r.randrange(5)
        ix, iv = self.intx()
        if op == 0:
            return self.add("shapes", f"{rd}.map(|s| grow(s, {ix}))", [grow(s, iv) for s in val])
        if op == 1:
            return self.add("shapes", f"{rd}.update(0, swap_kind).ok_or([])",
                            ([swap_kind(val[0])] + val[1:]) if val else [])
        if op == 2:
            s = self.shape_src()
            return self.add("shapes", f"{rd}.append({s[3]})", val + [s[2]])
        if op == 3:
            s = self.shape_src()
            return self.add("shapes", f"{rd}.set(0, {s[3]}).ok_or([])", ([s[2]] + val[1:]) if val else [])
        # read an element back out as a shape
        return self.add("shape", f"match {rd}.first() {{ Ok(s) => grow(s, {ix}), Err(_) => Dot }}",
                        grow(val[0], iv) if val else ("Dot",))

    def c_mk_item(self):
        sx, sv = self.strx()
        tx, tv = self.strx()
        ix, iv = self.intx()
        return self.add("item", f"{{ name: {sx}, tags: [{tx}], n: {ix} }}", {"name": sv, "tags": [tv], "n": iv})

    def item_src(self):
        v = self.pick("item")
        if v is None:
            self.c_mk_item()
            v = self.vars[-1]
        return v

    def c_item_op(self):
        nm, _, val, rd = self.item_src()
        op = self.r.randrange(5)
        sx, sv = self.strx()
        ix, iv = self.intx()
        if op == 0:
            return self.add("item", f"{{ ..{rd}, tags: {rd}.tags.append({sx}) }}", {**val, "tags": val["tags"] + [sv]})
        if op == 1:
            return self.add("item", f"rename_item({rd}, {sx})", {**val, "name": sv})
        if op == 2:
            cx, cv = self.cond("item", rd, val)
            nv = {**val, "n": val["n"] + iv}
            return self.add("item", f"if {cx} {rd} else {{ ..{rd}, n: {rd}.n + {ix} }}", val if cv else nv)
        if op == 3:
            s = self.shape_src()
            return self.add("shape", f"Circle({{ label: {rd}.name, r: {rd}.n }})",
                            ("Circle", {"label": val["name"], "r": val["n"]}))
        s = self.shape_src()
        return self.add("item", f"match {s[3]} {{ Circle(c) => {{ ..{rd}, name: c.label }}, other => {{ ..{rd}, n: r_of(other) }} }}",
                        ({**val, "name": s[2][1]["label"]} if s[2][0] == "Circle" else {**val, "n": r_of(s[2])}))

    def c_items(self):
        v = self.pick("items")
        if v is None or self.r.random() < 0.3:
            a = self.item_src()
            b = self.item_src()
            return self.add("items", f"[{a[3]}, {b[3]}]", [a[2], b[2]])
        nm, _, val, rd = v
        ix, iv = self.intx()
        sx, sv = self.strx()
        op = self.r.randrange(3)
        if op == 0:
            return self.add("items", f"{rd}.map(|i| {{ ..i, n: i.n + {ix} }})", [{**i, "n": i["n"] + iv} for i in val])
        if op == 1:
            return self.add("items", f"{rd}.map(|i| {{ ..i, tags: i.tags.append({sx}) }})",
                            [{**i, "tags": i["tags"] + [sv]} for i in val])
        return self.add("items", f"{rd}.update(0, |i| rename_item(i, {sx})).ok_or([])",
                        ([{**val[0], "name": sv}] + val[1:]) if val else [])

    def tree_src(self):
        v = self.pick("tree")
        if v is None:
            sx, sv = self.strx()
            k = self.r.randrange(10)
            self.add("tree", f"insert(Leaf, {k}, {sx})", insert(None, k, sv))
            v = self.vars[-1]
        return v

    def c_tree(self):
        nm, _, val, rd = self.tree_src()
        op = self.r.randrange(4)
        sx, sv = self.strx()
        k = self.r.randrange(10)
        if op == 0:
            return self.add("tree", f"insert({rd}, {k}, {sx})", insert(val, k, sv))
        if op == 1:
            return self.add("tree", f"bump({rd}, {k})", bump(val, k))
        if op == 2:
            return self.add("tree", f"rename_root({rd}, {sx})", rename_root(val, sv))
        cx, cv = ("z == 1", False) if self.r.random() < 0.5 else ("z == 0", True)
        return self.add("tree", f"if {cx} {rd} else bump({rd}, {k})", val if cv else bump(val, k))

    def c_capture(self):
        """A closure capturing a value; read through the closure at the end."""
        kind = self.r.choice(["shape", "item", "tree"])
        v = self.pick(kind)
        if v is None:
            return None
        nm, _, val, rd = v
        f = self.fresh("f")
        self.lines.append(f"\t{f} = |_u| {rd}")
        self.vars.append((f, kind, val, f"{f}({{}})"))
        return f

    def c_alias(self):
        if not self.vars:
            return None
        nm, kind, val, rd = self.r.choice(self.vars)
        return self.add(kind, rd, val, prefix="a")

    def c_var_loop(self):
        """A mutable variable rebuilt in a loop: a binding with several definitions."""
        nm, _, val, rd = self.shape_src()
        ks = [self.r.randrange(1, 9) for _ in range(self.r.randrange(1, 4))]
        sx, sv = self.strx()
        v = self.fresh("v")
        self.lines.append(f"\tvar ${v} = {rd}")
        self.lines.append(f"\tfor k in [{', '.join(str(k) for k in ks)}] {{")
        cur = val
        if self.r.random() < 0.5:
            lim = self.r.randrange(0, 9)
            self.lines.append(f"\t\t${v} = if k > {lim} ${v} else if k % 2 == 0 relabel(${v}, {sx}) else grow(${v}, k)")
            for k in ks:
                cur = cur if k > lim else (relabel(cur, sv) if k % 2 == 0 else grow(cur, k))
        else:
            self.lines.append(f"\t\t${v} = match ${v} {{ Circle({{ label, r }}) => if r > k ${v} else Circle({{ label: {sx}, r: r + k }}), "
                              f"Rect({{ label, pts }}) => Rect({{ label, pts: pts.append(k) }}), Dot => Dot }}")
            for k in ks:
                if cur[0] == "Circle":
                    cur = cur if cur[1]["r"] > k else ("Circle", {"label": sv, "r": cur[1]["r"] + k})
                elif cur[0] == "Rect":
                    cur = ("Rect", {"label": cur[1]["label"], "pts": cur[1]["pts"] + [k]})
        self.lines.append("\t}")
        return self.add("shape", f"${v}", cur)

    def c_early(self):
        nm, _, val, rd = self.shape_src()
        sx, sv = self.strx()
        cx, cv = ("z == 1", False) if self.r.random() < 0.5 else ("z == 0", True)
        if self.r.random() < 0.5:
            return self.add("shape", f"pick_label({rd}, {sx}, {cx})", val if cv else relabel(val, sv))
        n = self.r.randrange(0, 4)
        v = val
        for k in [1, 2, 3]:
            v = v if k > n else grow(v, k)
        return self.add("shape", f"loop_grow({rd}, {n})", v)

    def c_closure_all(self):
        """A join of tags inside a closure run by a builtin
        (https://github.com/roc-lang/roc/issues/13279)."""
        nm, _, val, rd = self.shape_src()
        sx, sv = self.strx()
        cx, cv = self.cond("shape", rd, val)
        alt = self.r.choice([("relabel(@, " + sx + ")", lambda x: relabel(x, sv)), ("swap_kind(@)", swap_kind)])
        joined = val if cv else alt[1](val)
        exp = show_shape(joined)
        b = self.r.random() < 0.5
        if not b:
            exp = exp + "x"
        e = f"[{{}}].all(|_| show_shape(if {cx} {rd} else {alt[0].replace("@", rd)}) == {roc_str(exp)})"
        return self.add("bool", e, b)

    def holder_src(self):
        v = self.pick("holder")
        if v is None:
            s = self.shape_src()
            ix, iv = self.intx()
            return self.add("holder", f"{{ sh: {s[3]}, k: {ix} }}", {"sh": s[2], "k": iv}) and self.vars[-1]
        return v

    def c_holder(self):
        nm, _, val, rd = self.holder_src()
        op = self.r.randrange(4)
        sx, sv = self.strx()
        ix, iv = self.intx()
        if op == 0:
            return self.add("holder", f"{{ ..{rd}, sh: grow({rd}.sh, {ix}) }}", {**val, "sh": grow(val["sh"], iv)})
        if op == 1:
            cx, cv = ("z == 1", False) if self.r.random() < 0.5 else ("z == 0", True)
            return self.add("holder", f"if {cx} {rd} else {{ sh: relabel({rd}.sh, {sx}), k: {rd}.k }}",
                            val if cv else {"sh": relabel(val["sh"], sv), "k": val["k"]})
        if op == 2:
            return self.add("shape", f"{rd}.sh", val["sh"])
        return self.add("holder", f"match {rd}.sh {{ Circle(c) => {{ sh: Rect({{ label: c.label, pts: [{rd}.k] }}), k: c.r }}, _ => {rd} }}",
                        ({"sh": ("Rect", {"label": val["sh"][1]["label"], "pts": [val["k"]]}), "k": val["sh"][1]["r"]}
                         if val["sh"][0] == "Circle" else val))

    def c_dismantle(self):
        """Move a field of a record into an in-place op; read the record again later."""
        nm, _, val, rd = self.item_src()
        sx, sv = self.strx()
        op = self.r.randrange(4)
        if op == 0:
            return self.add("strs", f"{rd}.tags.append({sx})", val["tags"] + [sv])
        if op == 1:
            return self.add("item", f"{{ ..{rd}, name: Str.concat({rd}.name, {sx}) }}", {**val, "name": val["name"] + sv})
        if op == 2:
            # destructure, rebuild with both refcounted fields moved
            return self.add("item", f"match {rd} {{ {{ name, tags, n }} => {{ name: Str.concat(name, {sx}), tags: tags.append(name), n }} }}",
                            {**val, "name": val["name"] + sv, "tags": val["tags"] + [val["name"]]})
        h = self.holder_src()
        return self.add("strs", f"[{rd}.name, label_of({h[3]}.sh)].append({sx})",
                        [val["name"], (h[2]["sh"][1]["label"] if h[2]["sh"][0] != "Dot" else ""), sv])

    def c_holders(self):
        v = self.pick("holders")
        if v is None or self.r.random() < 0.3:
            a = self.holder_src()
            b = self.holder_src()
            return self.add("holders", f"[{a[3]}, {b[3]}]", [a[2], b[2]])
        nm, _, val, rd = v
        sx, sv = self.strx()
        ix, iv = self.intx()
        op = self.r.randrange(3)
        if op == 0:
            return self.add("holders", f"{rd}.map(|h| {{ ..h, sh: relabel(h.sh, {sx}) }})",
                            [{**h, "sh": relabel(h["sh"], sv)} for h in val])
        if op == 1:
            lim = self.r.randrange(0, 12)
            return self.add("holders", f"{rd}.map(|h| if r_of(h.sh) > {lim} h else {{ sh: grow(h.sh, {ix}), k: h.k + 1 }})",
                            [h if r_of(h["sh"]) > lim else {"sh": grow(h["sh"], iv), "k": h["k"] + 1} for h in val])
        return self.add("holder", f"match {rd}.first() {{ Ok(h) => if label_of(h.sh).is_empty() h else {{ ..h, sh: swap_kind(h.sh) }}, Err(_) => {{ sh: Dot, k: 0 }} }}",
                        ((val[0] if (val[0]["sh"][0] == "Dot" or val[0]["sh"][1]["label"] == "") else {**val[0], "sh": swap_kind(val[0]["sh"])})
                         if val else {"sh": ("Dot",), "k": 0}))

    def c_selfop(self):
        """One operand consumes a value another operand borrows from."""
        op = self.r.randrange(6)
        if op <= 1:
            v = self.pick("strs")
            if v is None:
                it = self.item_src()
                return self.add("strs", f"{it[3]}.tags.concat({it[3]}.tags)", it[2]["tags"] + it[2]["tags"])
            nm, _, val, rd = v
            if op == 0:
                return self.add("strs", f"{rd}.append(match {rd}.first() {{ Ok(x) => x, Err(_) => \"\" }})",
                                val + [val[0] if val else ""])
            return self.add("strs", f"{rd}.set(0, match {rd}.last() {{ Ok(x) => x, Err(_) => \"\" }}).ok_or([])",
                            ([val[-1]] + val[1:]) if val else [])
        if op == 2:
            it = self.item_src()
            return self.add("item", f"{{ ..{it[3]}, name: Str.concat({it[3]}.name, {it[3]}.name) }}",
                            {**it[2], "name": it[2]["name"] * 2})
        if op == 3:
            v = self.pick("shapes")
            if v is None:
                return self.c_shape_list()
            nm, _, val, rd = v
            return self.add("shapes", f"{rd}.append(match {rd}.first() {{ Ok(s) => relabel(s, label_of(s)), Err(_) => Dot }})",
                            val + ([relabel(val[0], val[0][1]["label"]) if val[0][0] != "Dot" else val[0]] if val else [("Dot",)]))
        if op == 4:
            h = self.holder_src()
            return self.add("holder", f"{{ ..{h[3]}, sh: relabel({h[3]}.sh, Str.concat(label_of({h[3]}.sh), label_of({h[3]}.sh))) }}",
                            {**h[2], "sh": relabel(h[2]["sh"], (h[2]["sh"][1]["label"] * 2) if h[2]["sh"][0] != "Dot" else "")})
        it = self.item_src()
        return self.add("item", f"{{ ..{it[3]}, tags: {it[3]}.tags.append({it[3]}.name) }}",
                        {**it[2], "tags": it[2]["tags"] + [it[2]["name"]]})

    def strs_src(self):
        v = self.pick("strs")
        if v is None or self.r.random() < 0.25:
            sx, sv = self.strx()
            if self.r.random() < 0.5:
                k = self.r.randrange(50)
                return self.add("strs", f'["static-{k}", {sx}]', [f"static-{k}", sv]) and self.vars[-1]
            m = self.r.randrange(1, 3)
            return self.add("strs", f"List.repeat({sx}, {m})", [sv] * m) and self.vars[-1]
        return v

    def c_static_or_fresh(self):
        """Static data on one branch, a fresh list on the other, then an in-place op
        (https://github.com/roc-lang/roc/issues/12221)."""
        sx, sv = self.strx()
        k = self.r.randrange(50)
        m = self.r.randrange(1, 3)
        cx, cv = ("z == 1", False) if self.r.random() < 0.5 else ("z == 0", True)
        base = [f"static-{k}"] if cv else [sv] * m
        src = f'(if {cx} ["static-{k}"] else List.repeat({sx}, {m}))'
        op = self.r.randrange(3)
        if op == 0:
            return self.add("strs", f'{src}.append("tail")', base + ["tail"])
        if op == 1:
            return self.add("strs", f'{src}.concat(["c1", "c2"])', base + ["c1", "c2"])
        return self.add("strs", f'{src}.set(0, "set").ok_or([])', ["set"] + base[1:])

    def c_strs_alias_op(self):
        """An in-place op on one name while an alias of it stays live."""
        nm, _, val, rd = self.strs_src()
        self.add("strs", rd, val, prefix="a")
        sx, sv = self.strx()
        op = self.r.randrange(3)
        if op == 0:
            return self.add("strs", f"{rd}.append({sx})", val + [sv])
        if op == 1:
            return self.add("strs", f"{rd}.set(0, {sx}).ok_or([])", ([sv] + val[1:]) if val else [])
        w = self.strs_src()
        return self.add("strs", f"{rd}.concat({w[3]})", val + w[2])

    def c_dict(self):
        """A Dict built from a live list, or an insert into a Dict whose old value
        stays live through an alias or a record field
        (https://github.com/roc-lang/roc/issues/12834)."""
        v = self.pick("dict")
        k = f"k{self.r.randrange(3)}"
        w = self.strs_src()
        if v is None or self.r.random() < 0.3:
            return self.add("dict", f'Dict.empty().insert("{k}", {w[3]})', [(k, w[2])])
        nm, _, val, rd = v
        new = [(k2, (w[2] if k2 == k else v2)) for k2, v2 in val]
        if k not in dict(val):
            new.append((k, w[2]))
        if self.r.random() < 0.5:
            self.add("dict", rd, val, prefix="a")
            return self.add("dict", f'{rd}.insert("{k}", {w[3]})', new)
        h = self.fresh("holder")
        self.lines.append(f'\t{h} = {{ d: {rd}, note: "snap" }}')
        self.vars.append((h, "dict", val, f"{h}.d"))
        return self.add("dict", f'{h}.d.insert("{k}", {w[3]})', new)

    def program(self, size, focus=False):
        if focus:
            # joins of tags, closures, loops and dismantles only
            cs = [self.c_mk_shape, self.c_join_shape, self.c_join_shape, self.c_closure_all, self.c_closure_all,
                  self.c_var_loop, self.c_early, self.c_holder, self.c_holders, self.c_dismantle, self.c_capture,
                  self.c_alias, self.c_fold_shape, self.c_grow, self.c_selfop, self.c_selfop]
            for _ in range(size):
                self.r.choice(cs)()
            return self.render()
        cs = [self.c_mk_shape, self.c_grow, self.c_join_shape, self.c_join_shape, self.c_swap,
              self.c_fold_shape, self.c_shape_list, self.c_list_op, self.c_mk_item, self.c_item_op,
              self.c_items, self.c_tree, self.c_capture, self.c_alias,
              self.c_var_loop, self.c_var_loop, self.c_early, self.c_closure_all, self.c_holder, self.c_holder,
              self.c_dismantle, self.c_dismantle, self.c_holders, self.c_selfop, self.c_selfop,
              self.c_static_or_fresh, self.c_strs_alias_op, self.c_dict, self.c_dict]
        for _ in range(size):
            self.r.choice(cs)()
        return self.render()

    def render(self):
        inline = self.r.random() < 0.5
        if inline:
            # the whole body in one top-level expect block (issue 13279 needed
            # this: inside a function taking `z` the same closure compiled correctly)
            out = [PRELUDE, "expect {", "\tz = z0({})", '\tpad = "heap-allocated-string-padding-${z.to_str()}"']
        else:
            out = [PRELUDE, "run : U64, U64 -> Bool", "run = |z, which| {",
                   '\tpad = "heap-allocated-string-padding-${z.to_str()}"']
        out += self.lines
        checks = []
        for i, (nm, kind, val, rd) in enumerate(self.vars):
            exp = SHOW[kind](val)
            out.append(f"\tc{i} = {SHOW_FN[kind].format(rd)} == {roc_str(exp)}")
            checks.append(f"c{i}")
        if not checks:
            out.append("\tc0 = Bool.True")
            checks = ["c0"]
        if inline:
            out.append(f"\t{' and '.join(checks)}")
            out.append("}")
            return "\n".join(out) + "\n"
        out.append(f"\tchecks = [{', '.join(checks)}]")
        out.append(f"\tmatch checks.get(which) {{ Ok(ok) => ok, Err(_) => {' and '.join(checks)} }}")
        out.append("}")
        out.append("")
        for i in range(len(checks)):
            out.append(f"expect run(z0({{}}), {i})")
        return "\n".join(out) + "\n"


