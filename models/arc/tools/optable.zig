//! Prints the RcEffect row of every LowLevel op as lean/RocArc/OpTable.lean. Run by `./run.sh optable`.
const std = @import("std");
const LowLevel = @import("lowlevel").LowLevel;

pub fn main() void {
    const out = Out{};
    out.print("{s}", .{"-- GENERATED by tools/optable.zig from src/base/LowLevel.zig. Do not edit.\n"});
    out.print("{s}", .{"import RocArc.Syntax\nnamespace RocArc\n\ndef opTable : List (String × RcEffect) := [\n"});
    var first = true;
    for (std.enums.values(LowLevel)) |op| {
        const e = op.rcEffect();
        if (!first) out.print("{s}", .{",\n"});
        first = false;
        out.print("  (\"{s}\", {{ mayAllocate := {}, mayRetainOrRelease := {}, uniqCheck := {d}, consume := {d}, aliasConsumed := {d}, retain := {d}, retainResult := {}, borrowsArgs := {d}, sharesArgs := {d}, resultUnique := {}, reprArgs := {d}, deadLender := {s} }})", .{
            @tagName(op), e.may_allocate, e.may_retain_or_release, e.may_runtime_uniqueness_check_args, e.consume_args, e.result_aliases_consumed_args, e.retain_args, e.retain_result, e.result_borrows_args, e.result_shares_args, e.result_unique, op.representationArgs(), if (op.deadLenderArg()) |a| switch (a) { 0 => "some 0", 1 => "some 1", else => "none" } else "none",
        });
    }
    out.print("{s}", .{"\n]\n\nend RocArc\n"});
}

const Out = struct {
    fn print(_: Out, comptime fmt: []const u8, args: anytype) void {
        std.debug.print(fmt, args);
    }
};
