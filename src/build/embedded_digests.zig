//! Build-time SHA-256 digests of the files `roc` embeds as link inputs.
//!
//! `roc run` keys its cached host executables by the shim archive and default
//! platform objects it links, and those bytes are fixed when `roc` is built.
//! This tool digests each one once, at build time, and writes a Zig source
//! file declaring every digest as a named constant, so no `roc` invocation
//! ever rehashes the tens of megabytes it embeds.
//!
//! Usage: embedded_digests <output.zig> (<name> <file>)...

const std = @import("std");

const MainError = std.process.Args.ToSliceError || std.Io.Dir.ReadFileAllocError ||
    std.Io.Dir.WriteFileError || std.Io.Writer.Error || error{ OutOfMemory, ExpectedOutputAndNamedFiles };

/// Write the digest of each `<file>` in `args` as `pub const <name>` to `args[1]`.
pub fn main(init: std.process.Init) MainError!void {
    const gpa = init.gpa;
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    if (args.len < 2 or (args.len - 2) % 2 != 0) return error.ExpectedOutputAndNamedFiles;

    var out: std.Io.Writer.Allocating = .init(gpa);
    defer out.deinit();
    try out.writer.writeAll("//! Generated by src/build/embedded_digests.zig: the SHA-256 digest of each\n");
    try out.writer.writeAll("//! link input `roc` embeds.\n\n");

    var index: usize = 2;
    while (index < args.len) : (index += 2) {
        const bytes = try std.Io.Dir.cwd().readFileAlloc(init.io, args[index + 1], gpa, .unlimited);
        defer gpa.free(bytes);
        var digest: [std.crypto.hash.sha2.Sha256.digest_length]u8 = undefined;
        std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
        try out.writer.print("pub const {s} = [32]u8{{", .{args[index]});
        for (digest, 0..) |byte, byte_index| {
            try out.writer.print("{s}0x{x:0>2}", .{ if (byte_index == 0) " " else ", ", byte });
        }
        try out.writer.writeAll(" };\n");
    }

    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[1], .data = out.written() });
}
